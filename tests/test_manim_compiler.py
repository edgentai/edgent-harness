# ----------------------------------------------------------------------------- the prelude at run time
def _stub_manim() -> types.ModuleType:
    """Enough of Manim's surface for the prelude and a small film: bounding boxes, a time-advancing renderer, animations."""
    m = types.ModuleType("manim")

    class Config:
        frame_width, frame_height, pixel_width, pixel_height, frame_rate, quality, background_color = 14.222222222222221, 8.0, 854, 480, 15, "low_quality", "#000"

    class Renderer:
        def __init__(self) -> None:
            self.time = 0.0

    class Mobject:
        def __init__(self, x0: float = -0.5, y0: float = -0.5, x1: float = 0.5, y1: float = 0.5) -> None:
            self.box = [x0, y0, x1, y1]
            self.submobjects: list[Mobject] = []
            self.opacity = 1.0

        def _bbox(self) -> list[float]:
            if not self.submobjects:
                return list(self.box)
            boxes = [s._bbox() for s in self.submobjects] + ([list(self.box)] if self.has_points() else [])
            return [min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes)]

        def has_points(self) -> bool:
            return not self.submobjects

        @property
        def width(self) -> float:
            b = self._bbox()
            return b[2] - b[0]

        @property
        def height(self) -> float:
            b = self._bbox()
            return b[3] - b[1]

        def get_left(self) -> list[float]:
            b = self._bbox()
            return [b[0], (b[1] + b[3]) / 2, 0.0]

        def get_right(self) -> list[float]:
            b = self._bbox()
            return [b[2], (b[1] + b[3]) / 2, 0.0]

        def get_top(self) -> list[float]:
            b = self._bbox()
            return [(b[0] + b[2]) / 2, b[3], 0.0]

        def get_bottom(self) -> list[float]:
            b = self._bbox()
            return [(b[0] + b[2]) / 2, b[1], 0.0]

        def shift(self, v: list[float]) -> Mobject:
            self.box = [self.box[0] + v[0], self.box[1] + v[1], self.box[2] + v[0], self.box[3] + v[1]]
            for s in self.submobjects:
                s.shift(v)
            return self

        def scale(self, f: float) -> Mobject:
            b = self._bbox()
            cx, cy = (b[0] + b[2]) / 2, (b[1] + b[3]) / 2
            self.box = [cx + (self.box[0] - cx) * f, cy + (self.box[1] - cy) * f, cx + (self.box[2] - cx) * f, cy + (self.box[3] - cy) * f]
            for s in self.submobjects:
                s.scale(f)
            return self

        def move_to(self, p: list[float]) -> Mobject:
            b = self._bbox()
            return self.shift([p[0] - (b[0] + b[2]) / 2, p[1] - (b[1] + b[3]) / 2, 0.0])

        def get_fill_opacity(self) -> float:
            return self.opacity

        def set_opacity(self, o: float) -> Mobject:
            self.opacity = o
            return self

        def get_family(self) -> list[Mobject]:
            return [self] + [f for s in self.submobjects for f in s.get_family()]

        @property
        def animate(self) -> Builder:
            return Builder(self)

    class Builder:
        def __init__(self, mobject: Mobject) -> None:
            self.mobject = mobject

        def set_opacity(self, o: float) -> Animation:
            return Animation(self.mobject, run_time=1.0, effect=lambda: self.mobject.set_opacity(o))

    class Text(Mobject):
        def __init__(self, text: str, font_size: float = 48, color: str | None = None, **kw: object) -> None:
            w, h = len(text) * font_size * 0.012, font_size / 48 * 0.5
            super().__init__(-w / 2, -h / 2, w / 2, h / 2)
            self.text, self.original_text, self.font_size = text, text, font_size

    class Square(Mobject):
        def __init__(self, side_length: float = 2.0, **kw: object) -> None:
            super().__init__(-side_length / 2, -side_length / 2, side_length / 2, side_length / 2)

    class Dot(Mobject):
        def __init__(self, **kw: object) -> None:
            super().__init__(-0.08, -0.08, 0.08, 0.08)

    class VGroup(Mobject):
        def __init__(self, *subs: Mobject) -> None:
            super().__init__()
            self.submobjects = list(subs)

    class Arrow(Mobject):  # draws its own line and carries a tip: a container with points
        def __init__(self, start: list[float], end: list[float], **kw: object) -> None:
            super().__init__(min(start[0], end[0]), min(start[1], end[1]) - 0.05, max(start[0], end[0]), max(start[1], end[1]) + 0.05)
            tip = Mobject(end[0] - 0.3, end[1] - 0.15, end[0], end[1] + 0.15)
            self.submobjects = [tip]

        def has_points(self) -> bool:
            return True

    class Animation:
        def __init__(self, mobject: Mobject | None = None, run_time: float = 1.0, effect: object = None, **kw: object) -> None:
            self.mobject, self.run_time, self.effect = mobject, run_time, effect

    class Wait(Animation):
        def __init__(self, run_time: float = 1.0, **kw: object) -> None:
            super().__init__(None, run_time)

    class FadeIn(Animation):
        pass

    class Create(Animation):
        pass

    class Indicate(Animation):
        pass

    class FadeOut(Animation):
        pass

    class AnimationGroup(Animation):
        def __init__(self, *anims: Animation, **kw: object) -> None:
            super().__init__(None, max([a.run_time for a in anims] or [1.0]))
            self.anims = list(anims)

    class Scene:
        def __init__(self, renderer: object = None, **kw: object) -> None:
            self.mobjects: list[Mobject] = []
            self.renderer = Renderer()

        def add(self, *mobjects: Mobject) -> Scene:
            for mo in mobjects:
                if mo not in self.mobjects:
                    self.mobjects.append(mo)
            return self

        def remove(self, *mobjects: Mobject) -> Scene:
            self.mobjects = [mo for mo in self.mobjects if mo not in mobjects]
            return self

        def play(self, *args: Animation, **kwargs: object) -> None:
            flat = [a for arg in args for a in (arg.anims if isinstance(arg, AnimationGroup) else [arg])]
            for a in flat:
                if a.mobject is not None and not isinstance(a, FadeOut):
                    self.add(a.mobject)
            self.renderer.time += float(kwargs.get("run_time") or max([a.run_time for a in args] or [1.0]))  # type: ignore[arg-type]
            for a in flat:
                if a.effect:
                    a.effect()  # type: ignore[operator]
                if isinstance(a, FadeOut) and a.mobject is not None:
                    self.remove(a.mobject)

        def wait(self, duration: float = 1.0, **kw: object) -> None:
            self.play(Wait(run_time=duration))

        def construct(self) -> None:
            pass

        def tear_down(self) -> None:
            pass

    for name, value in list(locals().items()):
        if name[0].isupper() and name != "Config":
            setattr(m, name, value)
    m.config = Config()  # type: ignore[attr-defined]
    return m


