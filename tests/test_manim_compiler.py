def _run_scene(source: str, report_path: Path, monkeypatch: pytest.MonkeyPatch) -> dict:
    monkeypatch.setitem(sys.modules, "manim", _stub_manim())
    if importlib.util.find_spec("numpy") is None:  # the prelude only needs np.array for 3-vectors
        numpy = types.ModuleType("numpy")
        numpy.array = list  # type: ignore[attr-defined]
        monkeypatch.setitem(sys.modules, "numpy", numpy)
    monkeypatch.setenv(REPORT_ENV, str(report_path))
    namespace: dict = {"__name__": "scene"}
    exec(compile(source, "scene.py", "exec"), namespace)  # noqa: S102 - the generated scene, under a stub Manim
    return namespace


def test_generated_scene_runs_under_a_stub_manim(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    """The prelude's Film: counting plays, snapshots, the report written after every beat and at tear-down."""
    report_path = tmp_path / "report.json"
    source, warnings = mc.compile_storyboard(STUB_STORYBOARD)
    assert warnings == []
    film = _run_scene(source, report_path, monkeypatch)["GeneratedFilm"]()
    with pytest.raises(ValueError, match="boom"):
        film.construct()  # Manim would not reach tear_down; the beat wrote the report on its way out
    report = json.loads(report_path.read_text(encoding="utf-8"))
    assert report["scene"] == "GeneratedFilm" and report["complete"] is False and report["config"]["font_floor"] == FONT_FLOOR
    assert report["config"]["safe"]["margin"] == 0.6 and report["config"]["frame_width"] == pytest.approx(14.222, abs=0.001)
    beats = {b["id"]: b for b in report["beats"]}
    assert list(beats) == [1, 2, 3, 4] and [b["title"] for b in report["beats"]] == ["Setup", "Still", "Arrow", "Boom"]
    one = beats[1]
    assert one["plays"] == 1 and one["waits"] == 1 and one["error"] is None and one["duration_s"] == pytest.approx(3.4, abs=0.01)  # the title fade-in counts in the time, not as a play
    texts = {m["text"]: m for m in one["mobjects"] if m["kind"] == "text"}
    assert texts["Setup"]["role"] == "title" and texts["Setup"]["font_size"] == 56 and texts["a square"]["font_size"] == 32
    assert any(m["kind"] == "shape" and m["type"] == "Square" for m in one["mobjects"])
    assert beats[2]["plays"] == 0 and beats[2]["waits"] == 1 and beats[2]["adds"] == 1
    three = beats[3]
    assert three["plays"] == 2 and {m["type"] for m in three["mobjects"] if m["kind"] == "shape"} >= {"Arrow", "Mobject", "Dot", "Square"}
    assert [m for m in three["mobjects"] if m["type"] == "Square"][0]["opacity"] == 0.25  # focus() dimmed the square, kept the label
    assert beats[4]["error"] == "ValueError: boom" and beats[4]["plays"] == 1
    defects = measure(report, STUB_STORYBOARD)
    kinds = {(d["beat"], d["kind"]) for d in defects}
    assert {(2, "still_card"), (3, "outside_safe_frame"), (4, "beat_error"), (None, "render_incomplete")} <= kinds
    assert not any(k == "text_overlap" for _, k in kinds)
    assert any(d["detail"].startswith("Arrow crosses the safe frame on the left, right") for d in defects if d["kind"] == "outside_safe_frame")  # the container itself, not only its tip
    only_source, _ = mc.compile_storyboard(STUB_STORYBOARD, only=[1, 2, 3])
    film = _run_scene(only_source, report_path, monkeypatch)["GeneratedFilm"]()
    film.construct()
    film.tear_down()
    report = json.loads(report_path.read_text(encoding="utf-8"))
    assert report["complete"] is True and [b["id"] for b in report["beats"]] == [1, 2, 3] and report["total_s"] == pytest.approx(report["beats"][2]["end_s"])
    assert all(d["kind"] != "render_incomplete" for d in measure(report, STUB_STORYBOARD, only=[1, 2, 3]))
