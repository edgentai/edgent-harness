def _construct(source: str) -> ast.FunctionDef:
    tree = ast.parse(source)
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "GeneratedFilm")
    return next(n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == "construct")


def _beat_ids(construct: ast.FunctionDef) -> list[int]:
    return [n.items[0].context_expr.args[0].value for n in construct.body if isinstance(n, ast.With)]  # type: ignore[attr-defined]


def test_prelude_parses_and_defines_the_house_api():
    tree = ast.parse(PRELUDE_SOURCE)
    defined = {n.name for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
    defined |= {t.id for n in tree.body if isinstance(n, ast.Assign) for t in n.targets if isinstance(t, ast.Name)}
    expected = {"Film", "stage", "focus", "unfocus", "clamp_to_safe", "bbox", "TITLE", "BODY", "LABEL", "CAPTION", "FONT_FLOOR", "INK", "MUTED", "DIM", "ACCENT", "ACCENT_2", "BACKGROUND", "SAFE_MARGIN"}
    assert expected <= defined
    first_import = next(n for n in tree.body if isinstance(n, ast.ImportFrom))
    assert first_import.module == "manim" and first_import.names[0].name == "*"
    film = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Film")
    assert film.bases[0].id == "Scene"  # type: ignore[attr-defined]
    methods = {n.name for n in film.body if isinstance(n, ast.FunctionDef)}
    assert {"beat", "play", "add", "tear_down", "set_title", "_snapshot", "_write_report"} <= methods
    assert REPORT_ENV in PRELUDE_SOURCE and "SAFE_MARGIN = 0.6" in PRELUDE_SOURCE and f"CAPTION = {FONT_FLOOR}" in PRELUDE_SOURCE


def test_normalise_fills_defaults_and_allocates_stable_ids():
    sb = mc.normalise({"beats": [{"id": 4, "code": "self.wait(1)"}, {"title": "x"}, {"id": 2}]})
    assert sb["title"] == "Untitled film" and sb["persona"] == "" and sb["prelude"] == "" and sb["show_titles"] is True
    assert [b["id"] for b in sb["beats"]] == [4, 5, 2] and sb["next_beat_id"] == 6
    assert sb["beats"][1] == {"id": 5, "title": "x", "narration": "", "code": "", "seconds": None}
    assert mc.normalise(sb) == sb
    with pytest.raises(mc.CompileError, match="used twice"):
        mc.normalise({"beats": [{"id": 1}, {"id": 1}]})
    with pytest.raises(mc.CompileError, match="seconds"):
        mc.normalise({"beats": [{"seconds": "fast"}]})
    with pytest.raises(mc.CompileError, match="positive integer"):
        mc.normalise({"beats": [{"id": 0}]})
    with pytest.raises(mc.CompileError, match="list"):
        mc.normalise({"beats": "nope"})
    with pytest.raises(mc.CompileError, match="object"):
        mc.normalise([])  # type: ignore[arg-type]


