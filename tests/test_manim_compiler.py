def test_measure_hand_written_report():
    storyboard = {
        "beats": [
            {"id": 1, "title": "Setup", "seconds": 4, "code": "self.wait(1)"},
            {"id": 2, "title": "Squares", "narration": " ".join(["word"] * 26), "code": "self.add(Dot())"},
            {"id": 3, "title": "Never ran", "code": "self.wait(1)"},
        ]
    }
    defects = measure(_report(), storyboard)
    by_kind: dict[str, list[dict]] = {}
    for d in defects:
        by_kind.setdefault(d["kind"], []).append(d)
    assert set(by_kind) == {"text_overlap", "font_below_floor", "outside_safe_frame", "still_card", "duration_mismatch", "text_too_small", "missing_beat", "render_incomplete"}
    overlap = by_kind["text_overlap"]
    assert len(overlap) == 1 and overlap[0]["beat"] == 1 and {overlap[0]["a"], overlap[0]["b"]} == {"alpha", "\\beta"} and overlap[0]["severity"] == "error"
    floor = by_kind["font_below_floor"]
    assert len(floor) == 1 and floor[0]["font_size"] == 18 and floor[0]["severity"] == "error" and "tiny label" in floor[0]["detail"]
    outside = by_kind["outside_safe_frame"]
    assert len(outside) == 1 and outside[0]["sides"] == ["right"] and outside[0]["severity"] == "warn"
    still = by_kind["still_card"]
    assert len(still) == 1 and still[0]["beat"] == 2 and still[0]["severity"] == "error"
    mismatch = by_kind["duration_mismatch"]
    assert len(mismatch) == 1 and mismatch[0]["beat"] == 2 and mismatch[0]["source"] == "narration" and mismatch[0]["target_s"] == 10.0
    small = by_kind["text_too_small"]
    assert len(small) == 1 and small[0]["beat"] == 2 and small[0]["height_px"] < TEXT_HEIGHT_FLOOR_PX
    assert by_kind["missing_beat"][0]["beat"] == 3 and by_kind["render_incomplete"][0]["beat"] is None
    assert all(d["beat"] != 1 for d in defects if d["kind"] in ("still_card", "duration_mismatch"))
    report = _report()
    report["complete"] = True
    kinds = {d["kind"] for d in measure(report, storyboard, only=[1])}
    assert "missing_beat" not in kinds and "render_incomplete" not in kinds  # beat 3 was not expected; beat 2 is still measured
    assert measure(None, storyboard)[0]["kind"] == "no_report"
    assert measure({"complete": True, "beats": [{"id": 1, "error": "ValueError: boom", "plays": 1, "duration_s": 1.0}]}, {"beats": [{"id": 1}]})[0]["kind"] == "beat_error"


